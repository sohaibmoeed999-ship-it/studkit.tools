export function generateTwoColorTheme(config: TwoColorMixerConfig, name?: string): ThemeDefinition {
  const { color1, color2, balance, style } = config;

  // Derive darker and lighter shades
  const id = 'custom_' + Math.random().toString(36).substring(2, 9);

  return {
    id,
    name: name || `Custom (${color1} + ${color2})`,
    category: 'custom',
    isCustom: true,
    colors: {
      bgPrimary: color1,
      bgSurface: color1 === '#000000' || color1 === '#ffffff' ? (color1 === '#ffffff' ? '#f4f4f5' : '#0c0f17') : color1,
      bgSurfaceHover: color1 === '#ffffff' ? '#e4e4e7' : '#141a29',
      bgCard: color1 === '#ffffff' ? '#ffffff' : '#0f172a',
      borderColor: color1 === '#ffffff' ? '#e4e4e7' : '#1e293b',
      borderGlow: `${color2}44`,
      accentPrimary: color2,
      accentGlow: `${color2}66`,
      accentHover: color2,
      textPrimary: color1 === '#ffffff' ? '#09090b' : '#f8fafc',
      textMuted: color1 === '#ffffff' ? '#71717a' : '#94a3b8',
      accentDanger: '#ef4444',
      accentSuccess: '#10b981',
      accentWarning: '#f59e0b',
    },
  };
}
